(function () {
  'use strict';

  var VERT = [
    'attribute vec2 a_position;',
    'varying vec2 v_uv;',
    'void main() {',
    '  v_uv = a_position * 0.5 + 0.5;',
    '  gl_Position = vec4(a_position, 0.0, 1.0);',
    '}'
  ].join('\n');

  var NOISE_GLSL = [
    'vec3 mod289(vec3 x){return x-floor(x*(1.0/289.0))*289.0;}',
    'vec2 mod289(vec2 x){return x-floor(x*(1.0/289.0))*289.0;}',
    'vec3 permute(vec3 x){return mod289(((x*34.0)+1.0)*x);}',
    'float snoise(vec2 v){',
    '  const vec4 C=vec4(0.211324865405187,0.366025403784439,-0.577350269189626,0.024390243902439);',
    '  vec2 i=floor(v+dot(v,C.yy));',
    '  vec2 x0=v-i+dot(i,C.xx);',
    '  vec2 i1=(x0.x>x0.y)?vec2(1.0,0.0):vec2(0.0,1.0);',
    '  vec4 x12=x0.xyxy+C.xxzz;',
    '  x12.xy-=i1;',
    '  i=mod289(i);',
    '  vec3 p=permute(permute(i.y+vec3(0.0,i1.y,1.0))+i.x+vec3(0.0,i1.x,1.0));',
    '  vec3 m=max(0.5-vec3(dot(x0,x0),dot(x12.xy,x12.xy),dot(x12.zw,x12.zw)),0.0);',
    '  m=m*m;m=m*m;',
    '  vec3 x=2.0*fract(p*C.www)-1.0;',
    '  vec3 h=abs(x)-0.5;',
    '  vec3 ox=floor(x+0.5);',
    '  vec3 a0=x-ox;',
    '  m*=1.79284291400159-0.85373472095314*(a0*a0+h*h);',
    '  vec3 g;',
    '  g.x=a0.x*x0.x+h.x*x0.y;',
    '  g.yz=a0.yz*x12.xz+h.yz*x12.yw;',
    '  return 130.0*dot(m,g);',
    '}',
    'float fbm(vec2 p){',
    '  float v=0.0;',
    '  float a=0.5;',
    '  vec2 shift=vec2(100.0);',
    '  mat2 rot=mat2(cos(0.5),sin(0.5),-sin(0.5),cos(0.5));',
    '  for(int i=0;i<4;i++){',
    '    v+=a*snoise(p);',
    '    p=rot*p*2.0+shift;',
    '    a*=0.5;',
    '  }',
    '  return v;',
    '}'
  ].join('\n');

  var STUDIO_FRAG = [
    'precision highp float;',
    'varying vec2 v_uv;',
    'uniform float u_time;',
    'uniform vec2 u_resolution;',
    'uniform vec2 u_mouse;',
    'uniform float u_scroll;',
    NOISE_GLSL,
    'void main(){',
    '  vec2 uv=v_uv;',
    '  vec2 p=uv*2.0-1.0;',
    '  p.x*=u_resolution.x/u_resolution.y;',
    '  float t=u_time*0.12;',
    '  vec2 q=vec2(fbm(p*0.8+t*0.3),fbm(p*0.8+vec2(5.2,1.3)-t*0.2));',
    '  vec2 r=vec2(fbm(p*0.8+1.5*q+vec2(1.7,9.2)+0.15*t),fbm(p*0.8+1.5*q+vec2(8.3,2.8)-0.1*t));',
    '  float f=fbm(p*0.8+2.0*r);',
    '  vec3 c1=vec3(0.02,0.03,0.08);',
    '  vec3 c2=vec3(0.08,0.12,0.28);',
    '  vec3 c3=vec3(0.95,0.75,0.3);',
    '  vec3 c4=vec3(1.0,0.55,0.15);',
    '  vec3 c5=vec3(0.6,0.35,0.05);',
    '  vec3 col=mix(c1,c2,smoothstep(-0.3,0.5,f));',
    '  col=mix(col,c5,smoothstep(0.1,0.6,f)*0.5);',
    '  col=mix(col,c3,smoothstep(0.4,0.8,f)*0.35);',
    '  col=mix(col,c4,smoothstep(0.6,0.95,f)*0.25);',
    '  float glow=exp(-2.5*length(p-vec2(0.0,0.1)));',
    '  col+=c3*glow*0.08;',
    '  float vignette=1.0-dot(p*0.6,p*0.6);',
    '  col*=smoothstep(0.0,0.8,vignette);',
    '  col+=(fbm(uv*30.0+t*0.3)*0.5+0.5)*0.008;',
    '  gl_FragColor=vec4(col,1.0);',
    '}'
  ].join('\n');

  var INK_FRAG = [
    'precision highp float;',
    'varying vec2 v_uv;',
    'uniform float u_time;',
    'uniform vec2 u_resolution;',
    'uniform vec2 u_mouse;',
    'uniform float u_scroll;',
    NOISE_GLSL,
    'void main(){',
    '  vec2 uv=v_uv;',
    '  vec2 p=uv*2.0-1.0;',
    '  p.x*=u_resolution.x/u_resolution.y;',
    '  float t=u_time*0.06;',
    '  vec2 q=vec2(fbm(p*0.6+t*0.2),fbm(p*0.6+vec2(5.2,1.3)-t*0.15));',
    '  vec2 r=vec2(fbm(p*0.6+2.0*q+vec2(1.7,9.2)+0.1*t),fbm(p*0.6+2.0*q+vec2(8.3,2.8)-0.08*t));',
    '  float f=fbm(p*0.6+2.5*r);',
    '  vec3 paper=vec3(0.96,0.93,0.85);',
    '  vec3 paperDeep=vec3(0.92,0.88,0.76);',
    '  vec3 ink=vec3(0.12,0.10,0.08);',
    '  vec3 inkSoft=vec3(0.35,0.30,0.22);',
    '  vec3 col=mix(paper,paperDeep,smoothstep(-0.2,0.4,f));',
    '  float inkMask=smoothstep(0.3,0.7,f);',
    '  col=mix(col,inkSoft,inkMask*0.35);',
    '  col=mix(col,ink,smoothstep(0.55,0.9,f)*0.5);',
    '  float brush=smoothstep(0.015,0.0,abs(f-0.45))*0.25;',
    '  col=mix(col,ink,brush);',
    '  float vignette=1.0-dot(p*0.5,p*0.5);',
    '  col*=smoothstep(0.0,0.9,vignette);',
    '  col+=(fbm(uv*20.0)*0.5+0.5)*0.015;',
    '  gl_FragColor=vec4(col,1.0);',
    '}'
  ].join('\n');

  var SPACE_FRAG = [
    'precision highp float;',
    'varying vec2 v_uv;',
    'uniform float u_time;',
    'uniform vec2 u_resolution;',
    'uniform vec2 u_mouse;',
    'uniform float u_scroll;',
    NOISE_GLSL,
    'float hash(vec2 p){return fract(sin(dot(p,vec2(127.1,311.7)))*43758.5453);}',
    'void main(){',
    '  vec2 uv=v_uv;',
    '  vec2 p=uv*2.0-1.0;',
    '  p.x*=u_resolution.x/u_resolution.y;',
    '  float t=u_time*0.15;',
    '  vec3 bg=vec3(0.02,0.03,0.08);',
    '  vec3 cyan=vec3(0.0,0.9,0.9);',
    '  vec3 magenta=vec3(0.9,0.0,0.9);',
    '  vec3 gold=vec3(1.0,0.8,0.3);',
    '  vec3 col=bg;',
    '  float neb1=fbm(p*0.5+t*0.1);',
    '  float neb2=fbm(p*0.5+vec2(3.0,1.0)-t*0.08);',
    '  col+=cyan*smoothstep(0.2,0.8,neb1)*0.12;',
    '  col+=magenta*smoothstep(0.3,0.9,neb2)*0.1;',
    '  float stars=0.0;',
    '  for(int i=0;i<30;i++){',
    '    float fi=float(i);',
    '    vec2 sp=vec2(hash(vec2(fi,0.0)),hash(vec2(fi,1.0)));',
    '    sp.x=fract(sp.x+t*0.015*(0.3+hash(vec2(fi,2.0))));',
    '    float d=length(p-sp);',
    '    float brightness=hash(vec2(fi,3.0));',
    '    stars+=smoothstep(0.012,0.0,d)*brightness;',
    '  }',
    '  col+=stars*vec3(0.7,0.85,1.0)*0.5;',
    '  float wave=sin(p.x*6.0+t*1.5+fbm(p*2.0+t*0.5))*0.5+0.5;',
    '  col+=gold*wave*0.04;',
    '  float vignette=1.0-dot(p*0.6,p*0.6);',
    '  col*=smoothstep(0.0,0.8,vignette);',
    '  gl_FragColor=vec4(col,1.0);',
    '}'
  ].join('\n');

  var Shaders = {
    vertex: VERT,
    studio: STUDIO_FRAG,
    ink: INK_FRAG,
    space: SPACE_FRAG
  };

  window.Shaders = Shaders;
})();
